create index if not exists ilanlar_onay_durumu_idx on public.ilanlar(onay_durumu);
create index if not exists ilanlar_created_at_idx on public.ilanlar(created_at desc);

alter table public.ilanlar enable row level security;
create policy "onayli ilanlar herkese acik, sahibi ve yonetici hepsini gorur" on public.ilanlar
  for select using (
    onay_durumu = 'onaylandi'
    or ilan_veren_email = (select auth.jwt() ->> 'email')
    or (select auth.jwt() ->> 'email') in ('sadettinbal@gmail.com', 'mustafabal93@gmail.com')
  );

-- 5) Ziyaret istatistikleri (sadece sunucu okur/yazar)
create table if not exists public.ziyaretler (
  id bigint generated by default as identity primary key,
  sayfa text not null,
  firma_id integer references public.firmalar(id) on delete set null,
  referrer text,
  cihaz text,
  ip text,
  bolge text,
  created_at timestamptz not null default now()
);
create index if not exists ziyaretler_created_at_idx on public.ziyaretler(created_at);
create index if not exists ziyaretler_firma_id_idx on public.ziyaretler(firma_id);
alter table public.ziyaretler enable row level security;

-- 6) Reklamlar (herkes sadece aktif reklamları okur)
create table if not exists public.reklamlar (
  id bigint generated by default as identity primary key,
  baslik text not null default '',
  gorsel_url text not null,
  link_url text not null default '',
  konum text not null check (konum in ('video', 'sidebar', 'popup')),
  kategori text,
  aktif boolean not null default true,
  baslangic_tarihi timestamptz,
  bitis_tarihi timestamptz,
  siralama integer not null default 0,
  tiklanma integer not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists reklamlar_konum_aktif_idx on public.reklamlar(konum, aktif);
alter table public.reklamlar enable row level security;
create policy "aktif reklamlar herkese acik" on public.reklamlar for select using (aktif = true);

-- 7) Site içerikleri (örn. Site Kullanımı metni; sunucu okur/yazar)
create table if not exists public.site_icerikleri (
  anahtar text primary key,
  icerik text not null default '',
  guncelleme_tarihi timestamptz not null default now()
);
alter table public.site_icerikleri enable row level security;

-- 8) Google ile giriş yapan kullanıcılar (sunucu yazar; kullanıcı sadece kendi kaydını görür)
create table if not exists public.users (
  id bigint generated by default as identity primary key,
  google_id text not null unique,
  email text not null,
  name text not null,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz
);
create index if not exists users_email_idx on public.users(email);
alter table public.users enable row level security;
create policy "kullanici kendi kaydini gorur" on public.users
  for select to authenticated using ((select auth.uid())::text = google_id);

-- 9) "Üye Ol" başvuru formu (şifresiz başvuru; sunucu yazar)
