-- 1) Kovan'ın eski üye tablosu kenara alınır (silinmez); onu dolduran tetik kaldırılır
drop trigger if exists yeni_uye_kaydi on auth.users;
alter table if exists public.uyeler rename to uyeler_eski;

-- 2) Firmalar
create table if not exists public.firmalar (
  id integer generated by default as identity primary key,
  ad text not null,
  sahip text,
  sektor text,
  sanayi_sitesi text,
  adres text,
  telefon text,
  mobil_telefon text,
  hizmetler text[] not null default '{}',
  aciklama text,
  ozel_firma boolean not null default false,
  fotograf_url text,
  detay_fotograflar text[],
  onay_durumu text not null default 'onaylandi' check (onay_durumu in ('beklemede', 'onaylandi', 'reddedildi')),
  web_sitesi text,
  instagram text,
  facebook text,
  twitter text,
  youtube text,
  linkedin text,
  tiktok text,
  kullanici_email text,
  yeniden_gonderildi boolean,
  bekleyen_degisiklikler jsonb,
  guncelleme_talep_tarihi timestamptz,
  hedef_sayfa integer,
  -- Türkiye geneli (Kovan): konum ve kategori
  il_adi text,
  ilce_adi text,
  site_id integer references public.sanayi_siteleri(id) on delete set null,
  mahalle_id bigint,
  sokak_id integer,
  alt_kategori_id integer references public.alt_kategoriler(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz
);
create index if not exists firmalar_sanayi_sitesi_idx on public.firmalar(sanayi_sitesi);
create index if not exists firmalar_sektor_idx on public.firmalar(sektor);
create index if not exists firmalar_onay_durumu_idx on public.firmalar(onay_durumu);
create index if not exists firmalar_kullanici_email_idx on public.firmalar(kullanici_email);
create index if not exists firmalar_site_id_idx on public.firmalar(site_id);

alter table public.firmalar enable row level security;
create policy "onayli firmalar herkese acik, sahibi ve yonetici hepsini gorur" on public.firmalar
  for select using (
    onay_durumu = 'onaylandi'
    or kullanici_email = (select auth.jwt() ->> 'email')
    or (select auth.jwt() ->> 'email') in ('sadettinbal@gmail.com', 'mustafabal93@gmail.com')
  );

-- 3) Yorum ve puanlar (her kullanıcı bir firmaya bir kez)
create table if not exists public.yorumlar (
  id bigint generated by default as identity primary key,
  firma_id integer not null references public.firmalar(id) on delete cascade,
  kullanici_email text not null,
  kullanici_ad text not null default '',
  yorum text not null,
  puan integer not null check (puan between 1 and 5),
  created_at timestamptz not null default now()
);
create index if not exists yorumlar_firma_id_idx on public.yorumlar(firma_id);
create unique index if not exists yorumlar_unique_user_firma on public.yorumlar(firma_id, kullanici_email);

alter table public.yorumlar enable row level security;
create policy "yorumlar herkese acik" on public.yorumlar for select using (true);

-- 4) İlanlar
create table if not exists public.ilanlar (
  id bigint generated by default as identity primary key,
  baslik text not null,
  aciklama text not null,
  fiyat text,
  kategori text not null,
  telefon text not null,
  ilan_veren_ad text not null,
  ilan_veren_email text,
  fotograflar text[] not null default '{}',
  onay_durumu text not null default 'beklemede' check (onay_durumu in ('beklemede', 'onaylandi', 'reddedildi')),
  created_at timestamptz not null default now()
